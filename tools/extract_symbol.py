#!/usr/bin/env python3

import json
import sys
from pathlib import Path

import baserom as baserom_image

BYTES_PER_LINE = 12

def main() -> None:
    if len(sys.argv) != 6:
        sys.exit(f"usage: {sys.argv[0]} <baserom> <symbols.json> <extract.json> <symbol> <output>")
    baserom = Path(sys.argv[1])
    symbols_path = Path(sys.argv[2])
    extract_path = Path(sys.argv[3])
    symbol_name = sys.argv[4]
    output = Path(sys.argv[5])

    with open(extract_path, "r", encoding="utf-8") as f:
        entries = [e for e in json.load(f) if e["symbol"] == symbol_name]
    if len(entries) != 1:
        sys.exit(f"{extract_path}: expected one {symbol_name}, found {len(entries)}")
    entry = entries[0]
    size = int(entry["size"], 0)

    with open(symbols_path, "r", encoding="utf-8") as f:
        addresses = [s["address"] for s in json.load(f) if s["name"] == symbol_name]
    if len(addresses) != 1:
        sys.exit(f"{symbols_path}: expected one {symbol_name}, found {len(addresses)}")

    data = baserom_image.read(baserom, addresses[0], size)
    if len(data) != size:
        sys.exit(f"{baserom}: couldn't read {symbol_name}")

    text = "/*\n"
    text += f"{output.name.upper()}\n"
    text += "do not edit this file; it is machine-generated.\n"
    text += "*/\n"
    text += "\n"
    text += f"{entry['declaration']}= {{"
    for i, b in enumerate(data):
        if i % BYTES_PER_LINE == 0:
            text += "\n\t"
        text += f"0x{b:02x}, "
    text += "\n};\n"

    # Only rewrite when the contents change
    if output.is_file() and output.read_text(encoding="utf-8") == text:
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8", newline="\n")

if __name__ == "__main__":
    main()
