/* ---------- public code */

char const *dialogue_get_vocalization_name(
	short vocalization_type,
	boolean abbreviated)
{
	char const *name = "<error>";

	if (vocalization_type >= 0 && vocalization_type < NUMBER_OF_VOCALIZATION_TYPES)
	{
		name = dialogue_vocalization_type_name[vocalization_type][abbreviated];
	}

	return name;
}

short dialogue_get_vocalization_type_by_name(
	char const *name)
{
	short vocalization_type = NONE;
	short type_index;

	for (type_index = 0; type_index < NUMBER_OF_VOCALIZATION_TYPES; type_index++)
	{
		if (!strcmp(dialogue_vocalization_type_name[type_index][0], name))
		{
			vocalization_type = type_index;
			break;
		}
	}

	return vocalization_type;
}

